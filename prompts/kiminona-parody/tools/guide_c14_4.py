from PIL import Image, ImageDraw, ImageFont, ImageFilter
import sys, random
im=Image.open(sys.argv[1]).convert("RGB").resize((1920,1080))
im=im.filter(ImageFilter.GaussianBlur(2)).quantize(colors=22).convert("RGB")
d=ImageDraw.Draw(im)
f=ImageFont.truetype("/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf",26)
def lab(t,x,y): d.text((x,y),t,font=f,fill=(255,255,0),stroke_width=2,stroke_fill=(0,0,0))
skin=im.getpixel((900,520))
# chubbier lower face: wider cheeks + double chin (behind features)
d.ellipse([640,520,1240,880],fill=skin)
d.ellipse([760,800,1120,900],fill=skin)
d.arc([760,760,1120,880],10,170,fill=(170,120,100),width=4)
# nose + red cord
d.polygon([(945,470),(930,560),(965,560)],fill=(200,150,125))
d.line([(1772,0),(1762,540),(1750,1080)],fill=(215,40,30),width=26)
# redraw mouth (slightly open, surprised)
d.ellipse([895,640,985,690],fill=(150,70,70))
# snack crumbs around mouth
random.seed(2)
for _ in range(40):
    x=940+random.gauss(0,70); y=670+random.gauss(0,35); r=random.uniform(4,10)
    d.ellipse([x-r,y-r,x+r,y+r],fill=random.choice([(200,150,80),(230,190,110),(120,70,40)]))
# tears (glossy streaks)
d.line([(735,450),(745,560),(760,650)],fill=(225,235,245),width=6)
d.line([(1120,430),(1110,560)],fill=(225,235,245),width=6)
lab("STATIC close-up, 1.04s: subtle blink, tears roll",20,10)
lab("HEROINE (very plump): wide-eyed, teary, mouth slightly open",380,960)
lab("SNACK CRUMBS all around her mouth",380,995)
lab("tears on both cheeks",420,560)
lab("KEITA's blurred head (back),",1330,60)
lab("foreground right",1330,95)
lab("red cord hanging (as in ref)",1500,860)
lab("blurred white sleeve (foreground)",20,120)
lab("diagonal light: shadow on the right half of her face",380,1030)
